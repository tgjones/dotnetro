using System.CommandLine;
using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;

// generate-oscar64: the Oscar64 side of the reference corpus.
//
// Oscar64 (github.com/drmortalwombat/oscar64) is a whole-program C compiler for the
// 6502 that measures best on cross-compiler benchmarks, so it is a second reference
// next to llvm-mos. It only compiles whole programs, so each corpus case gets a
// generated harness: the case's source, a `__noinline` declaration of every function
// it defines (Oscar64 would otherwise inline them into `main`), out-of-line
// definitions for functions it only declares (`extern int g(int);`), and a `main`
// that calls each function with arguments read from `volatile` globals, so nothing
// is constant-folded. The compiled listing (`.asm`) is cut down to the case's own
// functions and written beside the case as `<name>.oscar64.asm`, which is checked
// in, like the llvm-mos `.s`; generate-report reads it from there.
//
// Oscar64 sees the whole harness, so it picks its own calling convention per
// function (parameters in zero page, a callee's arguments in A/X, ...). That is part
// of what is being measured, but it makes the smallest cases less like-for-like with
// llvm-mos, which compiles each function against a fixed ABI.
static class Oscar64Reference
{
    // A listing instruction line: `08a8 : 18 __ __ CLC` / `0882 : bd fc 08 LDA $08fc,x ; (…)`.
    static readonly Regex InstructionLine = new(@"^[0-9a-f]{4} : (?<bytes>(?:[0-9a-f_]{2} ){3})(?<mnemonic>[A-Z]{3})\b");
    // A function header in the listing: `add_i16: ; add_i16(i16,i16)->i16`.
    static readonly Regex FunctionHeader = new(@"^(?<name>[A-Za-z_]\w*): ;");
    // A source-reference line: `;   5, "/abs/path/to/file.c"` (dropped: it holds machine paths).
    static readonly Regex SourceLine = new(@"^;\s+\d+, """);

    public static Command Build()
    {
        var corpusOption = new Option<string?>("--corpus") { Description = "Path to ext/llvm-mos-reference (the corpus)." };
        var homeOption = new Option<string?>("--oscar64") { Description = "Oscar64 checkout with bin/oscar64 and include/ (default: $OSCAR64_HOME)." };
        var optOption = new Option<string?>("--opt") { Description = "Oscar64 optimization flag (default: -Os, matching the llvm-mos reference)." };

        var cmd = new Command("generate-oscar64", "Compile every corpus case with Oscar64 and write <case>.oscar64.asm beside it.");
        cmd.Options.Add(corpusOption);
        cmd.Options.Add(homeOption);
        cmd.Options.Add(optOption);
        cmd.SetAction(parse =>
        {
            var repoRoot = LocateRepoRoot();
            var corpus = parse.GetValue(corpusOption) ?? Path.Combine(repoRoot, "ext", "llvm-mos-reference");
            var home = parse.GetValue(homeOption) ?? Environment.GetEnvironmentVariable("OSCAR64_HOME");
            var opt = parse.GetValue(optOption) ?? "-Os";
            if (home is null) { Console.Error.WriteLine("Oscar64 not found: pass --oscar64 or set $OSCAR64_HOME"); return 1; }
            var compiler = Path.Combine(home, "bin", "oscar64");
            if (!File.Exists(compiler)) { Console.Error.WriteLine($"Oscar64 not found: {compiler} (build it with `make -C make compiler`)"); return 1; }
            var version = OscarVersion(home);

            var built = 0;
            var failed = new List<string>();
            foreach (var cFile in Directory.EnumerateFiles(corpus, "*.c", SearchOption.AllDirectories).OrderBy(p => p))
            {
                var label = Path.GetRelativePath(corpus, cFile);
                var listing = Compile(compiler, home, opt, cFile, out var error);
                var header = $"; Generated by irie-report generate-oscar64 ({version}, {opt} -n). Do not edit by hand.\n";
                var outFile = Path.ChangeExtension(cFile, ".oscar64.asm");
                if (listing is null)
                {
                    File.WriteAllText(outFile, header + "; oscar64 failed:\n" + string.Join('\n', error.Split('\n').Select(l => "; " + StripPaths(l, cFile)).Where(l => l != "; ")) + "\n");
                    failed.Add(label);
                    Console.WriteLine($"failed {label}");
                }
                else
                {
                    File.WriteAllText(outFile, header + listing);
                    built++;
                    Console.WriteLine($"built  {label}");
                }
            }
            Console.WriteLine($"Oscar64: {built} cases compiled, {failed.Count} failed{(failed.Count > 0 ? ": " + string.Join(", ", failed) : "")}.");
            return 0;
        });
        return cmd;
    }

    // Counts instructions and code bytes in a committed `.oscar64.asm`. Returns null
    // when the file records a compile failure (or holds no code).
    public static (int Instructions, int Bytes, string Display)? Count(string listing)
    {
        var instructions = 0;
        var bytes = 0;
        foreach (var line in listing.Replace("\r\n", "\n").Split('\n'))
        {
            var m = InstructionLine.Match(line);
            if (!m.Success || m.Groups["mnemonic"].Value == "BYT") continue;
            instructions++;
            bytes += m.Groups["bytes"].Value.Split(' ', StringSplitOptions.RemoveEmptyEntries).Count(b => b != "__");
        }
        if (instructions == 0) return null;
        var display = string.Join('\n', listing.Replace("\r\n", "\n").Split('\n').Where(l => !l.StartsWith("; Generated by", StringComparison.Ordinal))).Trim('\n');
        return (instructions, bytes, display);
    }

    // Builds the harness for one case, compiles it, and returns the listing of the
    // case's own functions (or null, with the compiler's output in `error`).
    static string? Compile(string compiler, string home, string opt, string cFile, out string error)
    {
        var source = StripComments(File.ReadAllText(cFile));
        var defined = ParseFunctions(source, @"\)\s*\{").ToList();
        var declared = ParseFunctions(source, @"\)\s*;")
            .Where(d => defined.All(f => f.Name != d.Name))
            .ToList();

        var work = Directory.CreateTempSubdirectory("irie-oscar64-");
        try
        {
            var harness = Path.Combine(work.FullName, "harness.c");
            File.WriteAllText(harness, BuildHarness(Path.GetFullPath(cFile), defined, declared, ParseGlobals(source)));
            var output = Path.Combine(work.FullName, "harness.prg");
            var (ok, log) = Run(compiler, $"-i={Path.Combine(home, "include")}", opt, "-n", $"-o={output}", harness);
            var asmFile = Path.ChangeExtension(output, ".asm");
            if (!ok || !File.Exists(asmFile)) { error = log; return null; }

            var listing = ExtractFunctions(File.ReadAllLines(asmFile), defined.Select(f => f.Name).ToHashSet());
            error = listing.Length == 0 ? "no listing for the case's functions\n" + log : "";
            return listing.Length == 0 ? null : listing;
        }
        finally { work.Delete(recursive: true); }
    }

    static string BuildHarness(string cFile, List<Function> defined, List<Function> declared, List<string> globals)
    {
        var sb = new StringBuilder();
        sb.Append($"#include \"{cFile}\"\n\n");
        sb.Append("volatile int o64_in;\nvolatile int o64_out;\n\n");

        // Oscar64 inlines small single-caller functions even at -Os; keep each case
        // function out of line so its code can be measured on its own.
        foreach (var f in defined)
            sb.Append($"__noinline {f.Return} {f.Name}({f.ParamList});\n");

        // Callees the case only declares (e.g. `extern int g(int);`) need a body.
        // It reads and writes volatiles so Oscar64 cannot treat it as pure.
        foreach (var f in declared)
        {
            var parameters = string.Join(", ", f.Params.Select((p, i) => $"{p} p{i}"));
            sb.Append($"__noinline {f.Return} {f.Name}({(f.Params.Count == 0 ? "void" : parameters)}) {{ ");
            for (var i = 0; i < f.Params.Count; i++) sb.Append($"o64_out = (int)p{i}; ");
            if (f.Return != "void") sb.Append($"return ({f.Return})o64_in; ");
            sb.Append("}\n");
        }
        sb.Append('\n');

        // One volatile global per argument and per result. A typedef makes
        // `volatile` qualify the whole type, pointers and structs included.
        var call = new StringBuilder();
        for (var fi = 0; fi < defined.Count; fi++)
        {
            var f = defined[fi];
            var args = new List<string>();
            for (var pi = 0; pi < f.Params.Count; pi++)
            {
                sb.Append($"typedef {f.Params[pi]} o64_t{fi}_{pi};\nvolatile o64_t{fi}_{pi} o64_a{fi}_{pi};\n");
                args.Add($"o64_a{fi}_{pi}");
            }
            var invoke = $"{f.Name}({string.Join(", ", args)})";
            if (f.Return == "void")
            {
                call.Append($"    {invoke};\n");
            }
            else
            {
                sb.Append($"typedef {f.Return} o64_r{fi}_t;\nvolatile o64_r{fi}_t o64_r{fi};\n");
                call.Append($"    o64_r{fi} = {invoke};\n");
            }
        }
        // Read the case's globals afterwards: Oscar64 sees the whole program and
        // would otherwise delete stores to globals nothing reads.
        foreach (var g in globals)
            call.Append($"    o64_out = (int){g};\n");
        sb.Append("\nint main(void)\n{\n").Append(call).Append("    return 0;\n}\n");
        return sb.ToString();
    }

    // Names of the case's top-level scalar globals: `int counter;`, `int g0, g1;`.
    static List<string> ParseGlobals(string source) =>
        Regex.Matches(source, @"^(?:unsigned\s+|signed\s+)?(?:char|short|int|long)(?:\s+(?:int|long))?\s+(?<names>[A-Za-z_]\w*(?:\s*,\s*[A-Za-z_]\w*)*)\s*;", RegexOptions.Multiline)
            .SelectMany(m => m.Groups["names"].Value.Split(',').Select(n => n.Trim()))
            .ToList();

    // Top-level function definitions (`terminator` = `{`) or declarations (`;`):
    // `<return type> <name>(<params>)`. The corpus is small, plain C, so a regex over
    // the comment-free source is enough.
    static IEnumerable<Function> ParseFunctions(string source, string terminator)
    {
        var re = new Regex(@"^(?<ret>(?:extern\s+|static\s+)?[A-Za-z_][\w\s\*]*?)\s*\b(?<name>[A-Za-z_]\w*)\s*\((?<params>[^()]*)" + terminator, RegexOptions.Multiline);
        foreach (Match m in re.Matches(source))
        {
            var ret = Regex.Replace(m.Groups["ret"].Value, @"\b(extern|static)\s+", "").Trim();
            var name = m.Groups["name"].Value;
            if (ret.Length == 0 || name is "if" or "for" or "while" or "switch" or "return") continue;
            var raw = m.Groups["params"].Value.Trim();
            var types = raw is "" or "void"
                ? new List<string>()
                : raw.Split(',').Select(p => ParamType(Regex.Replace(p, @"\s+", " ").Trim())).ToList();
            yield return new Function(Regex.Replace(ret, @"\s+", " "), name, types, raw is "" ? "void" : Regex.Replace(raw, @"\s+", " "));
        }
    }

    // `const int *a` → `const int *`; `int` (unnamed) stays `int`.
    static string ParamType(string param)
    {
        var m = Regex.Match(param, @"^(?<type>.*?[\s\*])(?<name>[A-Za-z_]\w*)$");
        var isNamed = m.Success && m.Groups["type"].Value.Trim().Length > 0
            && !Regex.IsMatch(m.Groups["name"].Value, @"^(int|char|long|short|unsigned|signed|void)$");
        return (isNamed ? m.Groups["type"].Value : param).Trim();
    }

    // Keeps only the listing sections of the given functions, minus source-reference
    // lines (they hold absolute paths).
    static string ExtractFunctions(string[] lines, HashSet<string> names)
    {
        var sb = new StringBuilder();
        var inSection = false;
        foreach (var line in lines)
        {
            var header = FunctionHeader.Match(line);
            if (header.Success) inSection = names.Contains(header.Groups["name"].Value);
            if (!inSection) continue;
            if (line.StartsWith("-----", StringComparison.Ordinal)) { inSection = false; sb.Append('\n'); continue; }
            if (SourceLine.IsMatch(line)) continue;
            sb.Append(line.TrimEnd()).Append('\n');
        }
        return sb.ToString().TrimEnd('\n') is { Length: > 0 } s ? s + "\n" : "";
    }

    static string StripComments(string source) =>
        Regex.Replace(Regex.Replace(source, @"/\*.*?\*/", " ", RegexOptions.Singleline), @"//[^\n]*", "");

    // Compiler errors name the harness and the case by absolute path; keep the file name.
    static string StripPaths(string line, string cFile) =>
        Regex.Replace(line.Replace(Path.GetFullPath(cFile), Path.GetFileName(cFile)), @"/\S*/(harness\.c)", "$1");

    static string OscarVersion(string home)
    {
        var (ok, sha) = Run("git", "-C", home, "rev-parse", "--short", "HEAD");
        return ok ? $"oscar64 {sha.Trim()}" : "oscar64";
    }

    static (bool Ok, string Output) Run(string exe, params string[] args)
    {
        var psi = new ProcessStartInfo(exe) { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
        foreach (var a in args) psi.ArgumentList.Add(a);
        using var p = Process.Start(psi)!;
        var stdout = p.StandardOutput.ReadToEndAsync();
        var stderr = p.StandardError.ReadToEnd();
        p.WaitForExit();
        return (p.ExitCode == 0, stdout.Result + stderr);
    }

    static string LocateRepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "DotNetro.slnx")))
            dir = dir.Parent;
        if (dir is null)
            throw new InvalidOperationException("could not locate src/ (DotNetro.slnx) above the running assembly.");
        return dir.Parent!.FullName;
    }

    record Function(string Return, string Name, List<string> Params, string ParamList);
}
